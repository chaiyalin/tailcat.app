export function detectLanguage() {
  try {
    const saved = localStorage.getItem("tailcat-language");
    if (saved === "zh" || saved === "en") return saved;
  } catch (_) {
    // Private browsing and restricted storage modes must still be usable.
  }
  return navigator.languages?.some((language) => language.toLowerCase().startsWith("zh")) ? "zh" : "en";
}

export function createI18n(initial = detectLanguage()) {
  let language = translations[initial] ? initial : "en";
  const translate = (key, values = {}) => {
    let text = translations[language][key] || translations.en[key] || key;
    for (const [name, value] of Object.entries(values)) {
      text = text.replaceAll(`{${name}}`, String(value));
    }
    return text;
  };
  const apply = (root = document) => {
    document.documentElement.lang = language === "zh" ? "zh-CN" : "en";
    document.title = translate("page_title");
    for (const element of root.querySelectorAll("[data-i18n]")) {
      element.textContent = translate(element.dataset.i18n);
    }
    for (const element of root.querySelectorAll("[data-i18n-placeholder]")) {
      element.placeholder = translate(element.dataset.i18nPlaceholder);
    }
    for (const element of root.querySelectorAll("[data-i18n-title]")) {
      const value = translate(element.dataset.i18nTitle);
      element.title = value;
      if (element.hasAttribute("aria-label")) element.setAttribute("aria-label", value);
    }
  };
  return {
    t: translate,
    apply,
    get language() { return language; },
    setLanguage(next) {
      if (!translations[next]) return;
      language = next;
      try {
        localStorage.setItem("tailcat-language", next);
      } catch (_) {
        // Keep the in-memory language even when site storage is unavailable.
      }
      apply();
    },
  };
}
